import { test, expect } from '@playwright/test';

test('portadas completas se amplían y cierran en escritorio y móvil', async ({ page }) => {
    await page.goto('./');
    for (const width of [1440, 320]) {
        await page.setViewportSize({ width, height: 900 });
        const abrir = page.getByRole('button', { name: 'Ampliar imagen de Battlefield 6', exact: true });
        await abrir.click();
        const visor = page.getByRole('dialog', { name: 'Battlefield 6', exact: true });
        await expect(visor).toBeVisible();
        const imagen = visor.getByRole('img', { name: 'Portada completa de Battlefield 6', exact: true });
        await expect(imagen).toBeVisible();
        await expect(visor.getByRole('heading', { name: 'Battlefield 6', exact: true })).toBeVisible();
        await expect(visor).toContainText('Combate a gran escala');
        await expect(visor).toContainText('$59.990');
        const posicionImagen = await imagen.boundingBox();
        const posicionDatos = await visor.locator('.visor-datos').boundingBox();
        if (width > 575) expect(posicionDatos.x).toBeGreaterThanOrEqual(posicionImagen.x + posicionImagen.width);
        else expect(posicionDatos.y).toBeGreaterThanOrEqual(posicionImagen.y + posicionImagen.height);
        expect(await imagen.evaluate(img => getComputedStyle(img).objectFit)).toBe('contain');
        const caja = await visor.boundingBox();
        expect(caja.width).toBeLessThanOrEqual(width);
        expect(caja.height).toBeLessThanOrEqual(900);
        const cantidadInicial = Number(await page.locator('#contadorCarrito').textContent());
        const agregar = visor.getByRole('button', { name: /Agregar al carrito|En el carrito/ });
        await agregar.click();
        await expect(agregar).toHaveText('En el carrito · +1');
        await agregar.click();
        await expect(page.locator('#contadorCarrito')).toHaveText(String(cantidadInicial + 2));
        await page.screenshot({ path: test.info().outputPath(`portada-${width}.png`) });
        await page.keyboard.press('Escape');
        await expect(visor).not.toBeVisible();
        await expect(abrir).toBeFocused();
        await abrir.click();
        await visor.getByRole('button', { name: 'Cerrar imagen', exact: true }).click();
        await expect(visor).not.toBeVisible();
        await expect(page.locator('#contadorCarrito')).toHaveText(String(cantidadInicial + 2));
    }
});

test('catálogo, cantidades, total y eliminación', async ({ page }) => {
    const errores = [];
    page.on('pageerror', error => errores.push(error.message));
    await page.goto('./');
    await expect(page.locator('.product-card')).toHaveCount(4);
    await expect(page.locator('#contadorCarrito')).toHaveText('0');
    await expect.poll(() => page.locator('.product-card img').first().evaluate(imagen => imagen.naturalWidth)).toBeGreaterThan(0);
    await page.screenshot({ path: test.info().outputPath('catalogo.png'), fullPage: true });
    const tarjeta = page.locator('.product-card').filter({ hasText: 'Battlefield 6' });
    await tarjeta.getByRole('button', { name: 'Agregar', exact: true }).click();
    await tarjeta.getByRole('button', { name: 'En el carrito · +1', exact: true }).click();
    await page.locator('.product-card').filter({ hasText: 'Helldivers II' }).getByRole('button', { name: 'Agregar', exact: true }).click();
    await expect(page.locator('#contadorCarrito')).toHaveText('3');
    await page.locator('[data-bs-target="#panelCarrito"]').click();
    await expect(page.locator('#panelCarrito')).toBeVisible();
    await expect(page.locator('#panelCarrito')).toHaveClass('offcanvas offcanvas-end text-bg-dark show');
    await expect(page.locator('#totalCarrito')).toHaveText(/159\.970/);
    await page.getByRole('button', { name: 'Aumentar cantidad de Battlefield 6', exact: true }).click();
    await expect(page.getByLabel('Unidades de Battlefield 6', { exact: true })).toHaveText('3');
    await expect(page.locator('#contadorCarrito')).toHaveText('4');
    await expect(page.locator('#totalCarrito')).toHaveText(/219\.960/);
    await page.getByRole('button', { name: 'Disminuir cantidad de Battlefield 6', exact: true }).click();
    await expect(page.getByLabel('Unidades de Battlefield 6', { exact: true })).toHaveText('2');
    await expect(page.locator('#totalCarrito')).toHaveText(/159\.970/);
    await page.getByRole('button', { name: 'Disminuir cantidad de Helldivers II', exact: true }).click();
    await expect(page.getByLabel('Cantidad de Helldivers II', { exact: true })).toHaveCount(0);
    await expect(page.locator('#contadorCarrito')).toHaveText('2');
    await expect(page.locator('#totalCarrito')).toHaveText(/119\.980/);
    await page.getByRole('button', { name: 'Cerrar carrito', exact: true }).click();
    await page.locator('.product-card').filter({ hasText: 'Helldivers II' }).getByRole('button', { name: 'Agregar', exact: true }).click();
    await page.locator('[data-bs-target="#panelCarrito"]').click();
    await expect(page.locator('#totalCarrito')).toHaveText(/159\.970/);
    await page.screenshot({ path: test.info().outputPath('carrito.png'), fullPage: false, animations: 'disabled' });
    await page.getByRole('button', { name: 'Eliminar Battlefield 6', exact: true }).click();
    await expect(page.locator('#contadorCarrito')).toHaveText('1');
    await expect(page.locator('#totalCarrito')).toHaveText(/39\.990/);
    await page.getByRole('button', { name: 'Vaciar carrito', exact: true }).click();
    await expect(page.getByText('Tu carrito está vacío.', { exact: true })).toBeVisible();
    await expect(page.locator('#contadorCarrito')).toHaveText('0');
    await expect(page.getByRole('button', { name: 'Vaciar carrito', exact: true })).toBeDisabled();
    await page.screenshot({ path: test.info().outputPath('carrito-vacio.png'), fullPage: false, animations: 'disabled' });
    expect(errores).toEqual([]);
});

test('búsqueda combinada con categorías y vista móvil', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('./');
    await expect(page.locator('.product-card')).toHaveCount(4);
    await page.getByRole('button', { name: 'Aventura', exact: true }).click();
    await expect(page.locator('.product-card')).toHaveCount(2);
    await expect(page.locator('.product-card').filter({ hasText: 'Returnal' })).toHaveCount(1);
    await expect(page.locator('.product-card').filter({ hasText: 'Shadow of the Colossus' })).toHaveCount(1);
    await page.getByRole('searchbox').fill('Battlefield');
    await page.getByRole('button', { name: 'Buscar', exact: true }).click();
    await expect(page.getByText('No encontramos productos con esa búsqueda.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Todos', exact: true }).click();
    await expect(page.locator('.product-card')).toHaveCount(1);
    await page.getByRole('searchbox').fill('');
    await expect(page.locator('.product-card')).toHaveCount(4);
    await page.getByRole('button', { name: 'Abrir menú', exact: true }).click();
    await page.locator('[data-bs-target="#panelCarrito"]').click();
    await expect(page.getByText('Tu carrito está vacío.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Cerrar carrito', exact: true }).click();
    await expect(page.locator('#panelCarrito')).not.toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('movil.png'), fullPage: true });
});

test('error de carga y recuperación mediante reintento', async ({ page }) => {
    let fallar = true;
    await page.route('**/productos-*.json', route => fallar ? route.fulfill({ status: 503, body: 'No disponible' }) : route.continue());
    await page.goto('./');
    await expect(page.getByText('No fue posible cargar el catálogo.', { exact: false })).toBeVisible();
    await expect(page.locator('.product-card')).toHaveCount(0);
    await page.screenshot({ path: test.info().outputPath('error.png'), fullPage: true });
    fallar = false;
    await page.getByRole('button', { name: 'Reintentar', exact: true }).click();
    await expect(page.locator('.product-card')).toHaveCount(4);
    await expect(page.getByRole('button', { name: 'Reintentar', exact: true })).toHaveCount(0);
});
